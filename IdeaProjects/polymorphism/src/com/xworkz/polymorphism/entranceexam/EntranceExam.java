package com.xworkz.polymorphism.entranceexam;

public class EntranceExam {

        public void register() {
            System.out.println("Entrance Exam: Registering for the exam.");
        }

        public void prepare() {
            System.out.println("Entrance Exam: Preparing through study and practice.");
        }

        public void appear() {
            System.out.println("Entrance Exam: Appearing for the written examination.");
        }

        public void result() {
            System.out.println("Entrance Exam: Waiting for the result declaration.");
        }

        public void counseling() {
            System.out.println("Entrance Exam: Attending counseling or interview after result.");
        }
    }


