package com.xworkz.polymorphism.amphibian;

public class Amphibian {
        public void breathe() {
            System.out.println("Amphibian: Breathing through skin and lungs");
        }

        public void move() {
            System.out.println("Amphibian: Moving in water and on land");
        }

        public void reproduce() {
            System.out.println("Amphibian: Laying eggs in water");
        }

        public void habitat() {
            System.out.println("Amphibian: Living in moist environments");
        }

        public void survive() {
            System.out.println("Amphibian: Adapting to both water and land");
        }
    }


