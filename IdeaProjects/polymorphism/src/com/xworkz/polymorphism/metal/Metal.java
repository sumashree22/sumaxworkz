package com.xworkz.polymorphism.metal;

public class Metal {

        public void conductHeat() {
            System.out.println("Metal: Conducting heat efficiently.");
        }

        public void conductElectricity() {
            System.out.println("Metal: Conducting electricity.");
        }

        public void melt() {
            System.out.println("Metal: Melting at a high temperature.");
        }

        public void shine() {
            System.out.println("Metal: Shining with a metallic luster.");
        }

        public void beMolded() {
            System.out.println("Metal: Can be molded into different shapes.");
        }
    }


