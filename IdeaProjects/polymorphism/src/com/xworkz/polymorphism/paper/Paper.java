package com.xworkz.polymorphism.paper;

public class Paper {
        public void create() {
            System.out.println("Paper: Creating a blank sheet of paper.");
        }

        public void print() {
            System.out.println("Paper: Printing content on the paper.");
        }

        public void fold() {
            System.out.println("Paper: Folding the paper.");
        }

        public void recycle() {
            System.out.println("Paper: Recycling the used paper.");
        }

        public void use() {
            System.out.println("Paper: Using the paper for writing or printing.");
        }
    }


