package com.xworkz.polymorphism.rose;

public class Rose {
    public void start() {
        System.out.println("Rose: Starting");
    }

    public void configure() {
        System.out.println("Rose: Configuring");
    }

    public void execute() {
        System.out.println("Rose: Executing task");
    }

    public void stop() {
        System.out.println("Rose: Stopping");
    }
}
