package com.xworkz.polymorphism.sun;

public class Sun {
    public void start() {
        System.out.println("Sun: Starting");
    }

    public void configure() {
        System.out.println("Sun: Configuring");
    }

    public void execute() {
        System.out.println("Sun: Executing task");
    }

    public void stop() {
        System.out.println("Sun: Stopping");
    }
}
