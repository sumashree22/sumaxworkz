package com.xworkz.polymorphism.bird;

public class Bird {
    public void eat() {
        System.out.println("Animal: Executing eat");
    }
    public void sleep() {
        System.out.println("Animal: Executing sleep");
    }
    public void fly() {
        System.out.println("Animal: Executing fly");
    }
    public void chirp() {
        System.out.println("Animal: Executing chirp");
    }
}
