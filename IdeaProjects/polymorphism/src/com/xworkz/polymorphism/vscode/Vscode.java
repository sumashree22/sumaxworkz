package com.xworkz.polymorphism.vscode;

public class Vscode {
    public void start() {
        System.out.println("Vscode: Starting");
    }

    public void configure() {
        System.out.println("Vscode: Configuring");
    }

    public void execute() {
        System.out.println("Vscode: Executing task");
    }

    public void stop() {
        System.out.println("Vscode: Stopping");
    }
}
