public class SocialMedia {

        public void connect() {
            System.out.println("Social Media: Connecting people worldwide.");
        }

        public void shareContent() {
            System.out.println("Social Media: Allowing users to share content like photos, videos, and posts.");
        }

        public void interact() {
            System.out.println("Social Media: Users interact via comments, likes, and messages.");
        }

        public void network() {
            System.out.println("Social Media: Building and maintaining social networks.");
        }

        public void updateStatus() {
            System.out.println("Social Media: Users can update their status and share thoughts.");
        }
    }


