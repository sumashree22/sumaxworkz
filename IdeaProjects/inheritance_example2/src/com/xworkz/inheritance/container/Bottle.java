package com.xworkz.inheritance.container;

public class Bottle extends Container{

        public void fill() { System.out.println("Filling bottle"); }
        public void empty() { System.out.println("Emptying bottle"); }
        public void clean() { System.out.println("Cleaning bottle"); }
        public void store() { System.out.println("Storing bottle"); }
        public void seal() { System.out.println("Sealing bottle"); }

}
