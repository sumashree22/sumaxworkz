package com.xworkz.polymorphism.bankAccount;

public class BankAccount {

        public void openAccount() {
            System.out.println("Bank Account: Opening a new bank account.");
        }

        public void deposit() {
            System.out.println("Bank Account: Depositing money into the account.");
        }

        public void withdraw() {
            System.out.println("Bank Account: Withdrawing money from the account.");
        }

        public void checkBalance() {
            System.out.println("Bank Account: Checking account balance.");
        }

        public void closeAccount() {
            System.out.println("Bank Account: Closing the bank account.");
        }
    }


