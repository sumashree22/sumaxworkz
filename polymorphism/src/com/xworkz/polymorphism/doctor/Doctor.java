public class Doctor {
    public void start() {
        System.out.println("Doctor: Starting");
    }

    public void configure() {
        System.out.println("Doctor: Configuring");
    }

    public void execute() {
        System.out.println("Doctor: Executing task");
    }

    public void stop() {
        System.out.println("Doctor: Stopping");
    }
}
