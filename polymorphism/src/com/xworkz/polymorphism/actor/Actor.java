package com.xworkz.polymorphism.actor;

public class Actor {
        public void arrive() {
            System.out.println("Actor: Arriving on set");
        }

        public void rehearse() {
            System.out.println("Actor: Rehearsing lines");
        }

        public void perform() {
            System.out.println("Actor: Performing in scene");
        }

        public void wrapUp() {
            System.out.println("Actor: Wrapping up shoot");
        }

        public void giveInterview() {
            System.out.println("Actor: Giving interview");
        }
    }


