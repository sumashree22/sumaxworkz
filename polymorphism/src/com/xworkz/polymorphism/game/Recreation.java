package com.xworkz.polymorphism.game;

public class Recreation {
    public void play() {
        System.out.println("Recreation: Executing play");
    }
    public void pause() {
        System.out.println("Recreation: Executing pause");
    }
    public void restart() {
        System.out.println("Recreation: Executing restart");
    }
    public void end() {
        System.out.println("Recreation: Executing end");
    }
}
