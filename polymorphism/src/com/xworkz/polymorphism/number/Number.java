package com.xworkz.polymorphism.number;

public class Number {
        public void value() {
            System.out.println("Number: A numeric value used for counting or measurement.");
        }

        public void add() {
            System.out.println("Number: Can be added to other numbers to get a sum.");
        }

        public void subtract() {
            System.out.println("Number: Can be subtracted from other numbers to get a difference.");
        }

        public void multiply() {
            System.out.println("Number: Can be multiplied with other numbers to get a product.");
        }

        public void divide() {
            System.out.println("Number: Can be divided by other numbers to get a quotient.");
        }
    }


