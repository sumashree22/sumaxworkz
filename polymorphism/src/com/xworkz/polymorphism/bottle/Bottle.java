package com.xworkz.polymorphism.bottle;

public class Bottle {
    public void start() {
        System.out.println("Bottle: Starting");
    }

    public void configure() {
        System.out.println("Bottle: Configuring");
    }

    public void execute() {
        System.out.println("Bottle: Executing task");
    }

    public void stop() {
        System.out.println("Bottle: Stopping");
    }
}
